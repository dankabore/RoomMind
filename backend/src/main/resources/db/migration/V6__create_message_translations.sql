-- Saved translations, so each message is sent to the model at most once per
-- language. Every reader of that language gets the same saved text: a
-- translation depends on the message and the language, not on who asked.
create table message_translations (
    id          bigint      generated by default as identity primary key,

    -- "on delete cascade": when a group ends its messages are deleted in one
    -- statement, and the database removes their translations with them, so
    -- that code does not need to know translations exist.
    message_id  bigint      not null references messages (id) on delete cascade,

    -- The same codes, and the same check, as users.language.
    language    varchar(5)  not null,

    -- text, like summaries: the model decides the length, and a translation
    -- can come out longer than the 4000-character original.
    translation text        not null,

    created_at  timestamptz not null default now(),

    -- One translation per message and language. Besides keeping duplicates
    -- out, this is the index the lookup uses.
    constraint uq_message_translations unique (message_id, language),

    constraint chk_message_translations_language check (
        language in ('EN', 'FR', 'ES', 'DE', 'IT', 'PT', 'AR', 'ZH')
    )
);
